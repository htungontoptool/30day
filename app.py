def _txt_dice(meta):
    dice = meta.get('dice') if isinstance(meta, dict) else None
    if not isinstance(dice, (list, tuple)):
        dice = []
    parts = []
    for x in dice[:3]:
        try:
            d = int(x)
            if d < 1 or d > 6: return None
            parts.append(d)
        except (TypeError, ValueError):
            return None
    return parts if len(parts) == 3 else None


